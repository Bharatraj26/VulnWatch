"""
VulnWatch — Automated PDF Security Report Generator
===================================================
Generates comprehensive, professional PDF security audit reports from actual
scan records and findings using ReportLab. Pure local generation with no cloud APIs.
"""

from __future__ import annotations

import html
import io
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.pdfgen import canvas
from reportlab.platypus import (
    HRFlowable,
    KeepTogether,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


def _esc(val: Any) -> str:
    """Safely escape text for ReportLab XML/HTML Paragraph formatting."""
    if val is None:
        return ""
    return html.escape(str(val))


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and display total page count."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict[str, Any]] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_decorations(self, page_count: int) -> None:
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Running header (pages 2+)
        if self._pageNumber > 1:
            self.drawString(
                54,
                letter[1] - 36,
                "VulnWatch Security Audit Report — Confidential / Educational",
            )
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(54, letter[1] - 42, letter[0] - 54, letter[1] - 42)

        # Running footer (all pages)
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(54, 45, letter[0] - 54, 45)

        footer_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 54, 32, footer_text)
        self.drawString(
            54,
            32,
            "Generated by VulnWatch — Automated Web Security Testing & CI/CD Platform",
        )
        self.restoreState()


# Severity color scheme
SEVERITY_COLORS = {
    "critical": colors.HexColor("#991b1b"),  # deep crimson
    "high": colors.HexColor("#c2410c"),      # dark orange
    "medium": colors.HexColor("#b45309"),    # amber/gold
    "low": colors.HexColor("#1e40af"),       # dark cobalt blue
    "info": colors.HexColor("#475569"),      # slate
}

SEVERITY_BG_COLORS = {
    "critical": colors.HexColor("#fee2e2"),
    "high": colors.HexColor("#ffedd5"),
    "medium": colors.HexColor("#fef3c7"),
    "low": colors.HexColor("#dbeafe"),
    "info": colors.HexColor("#f1f5f9"),
}


def generate_report_pdf(report: dict[str, Any]) -> bytes:
    """
    Generate a complete, professional security audit PDF report from a report dictionary.
    Returns PDF content as raw bytes.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom typography styles
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#0f172a"),
        spaceAfter=4,
    )

    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#475569"),
        spaceAfter=14,
    )

    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=16,
        textColor=colors.HexColor("#0f172a"),
        spaceBefore=14,
        spaceAfter=8,
    )

    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#1e293b"),
    )

    code_style = ParagraphStyle(
        "ReportCode",
        parent=styles["Normal"],
        fontName="Courier",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#0f172a"),
    )

    meta_label = ParagraphStyle(
        "MetaLabel",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#475569"),
    )

    meta_val = ParagraphStyle(
        "MetaVal",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#0f172a"),
    )

    story: list[Any] = []

    # ── 1. Document Header ─────────────────────────────────────────────────────
    story.append(Paragraph("VulnWatch Security Assessment Report", title_style))
    story.append(
        Paragraph(
            "Automated Web Security Audit & Passive Vulnerability Evaluation",
            subtitle_style,
        )
    )
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0f172a"), spaceAfter=14))

    # ── 2. Metadata Table ──────────────────────────────────────────────────────
    report_id = _esc(report.get("id", "N/A"))
    scan_id = _esc(report.get("scanId") or report.get("scan_id", "N/A"))
    target_url = _esc(report.get("target", "N/A"))
    scanned_at = _esc(report.get("scannedAt") or report.get("scanned_at", "N/A"))
    score = report.get("securityScore") if "securityScore" in report else report.get("security_score", 0)
    try:
        score_val = int(score)
    except (TypeError, ValueError):
        score_val = 0
    score_val = max(0, min(100, score_val))

    status = _esc(str(report.get("status") or "completed").upper())

    # Determine grade from score
    if score_val >= 85:
        grade = "A"
        grade_color = colors.HexColor("#15803d")
    elif score_val >= 70:
        grade = "B"
        grade_color = colors.HexColor("#16a34a")
    elif score_val >= 50:
        grade = "C"
        grade_color = colors.HexColor("#b45309")
    elif score_val >= 30:
        grade = "D"
        grade_color = colors.HexColor("#c2410c")
    else:
        grade = "F"
        grade_color = colors.HexColor("#b91c1c")

    meta_data = [
        [
            Paragraph("Report ID", meta_label),
            Paragraph(f"<font name='Courier'>{report_id}</font>", meta_val),
            Paragraph("Assessment Score", meta_label),
            Paragraph(f"<b><font color='{grade_color.hexval()}'>{score_val} / 100 (Grade {grade})</font></b>", meta_val),
        ],
        [
            Paragraph("Scan ID", meta_label),
            Paragraph(f"<font name='Courier'>{scan_id}</font>", meta_val),
            Paragraph("Scan Status", meta_label),
            Paragraph(f"<b>{status}</b>", meta_val),
        ],
        [
            Paragraph("Target URL", meta_label),
            Paragraph(f"<font name='Courier'>{target_url}</font>", meta_val),
            Paragraph("Scan Timestamp", meta_label),
            Paragraph(scanned_at, meta_val),
        ],
    ]

    meta_table = Table(meta_data, colWidths=[1.2 * inch, 2.3 * inch, 1.2 * inch, 2.3 * inch])
    meta_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ])
    )
    story.append(meta_table)
    story.append(Spacer(1, 14))

    # ── 3. Executive Summary ───────────────────────────────────────────────────
    story.append(Paragraph("Executive Summary", section_heading))
    summary_text = _esc(report.get("summary") or "No executive summary available for this scan.")
    story.append(Paragraph(summary_text, body_style))
    story.append(Spacer(1, 10))

    # ── 4. Scoring Methodology ─────────────────────────────────────────────────
    methodology_text = (
        "<b>Scoring Methodology:</b> VulnWatch employs a transparent, deterministic deduction model from a baseline of "
        "100 points: Critical severity findings deduct 25 points; High deducts 15 points; Medium deducts 8 points; "
        "Low deducts 3 points; Informational observations incur 0 points. "
        "Final score = <i>max(0, min(100, 100 - total deductions))</i>. "
        "Grade Scale: 85–100 (Grade A), 70–84 (Grade B), 50–69 (Grade C), 30–49 (Grade D), 0–29 (Grade F)."
    )
    story.append(Paragraph(methodology_text, body_style))
    story.append(Spacer(1, 14))

    # ── 5. Severity Distribution ───────────────────────────────────────────────
    story.append(Paragraph("Severity Distribution & Observation Breakdown", section_heading))

    sev_breakdown = report.get("severityBreakdown") or report.get("severity_breakdown") or {}
    crit_count = sev_breakdown.get("critical", 0)
    high_count = sev_breakdown.get("high", 0)
    med_count = sev_breakdown.get("medium", 0)
    low_count = sev_breakdown.get("low", 0)
    info_count = sev_breakdown.get("info", 0)
    total_findings = crit_count + high_count + med_count + low_count + info_count

    sev_table_data = [
        [
            Paragraph("<b>Severity</b>", meta_label),
            Paragraph("<b>Count</b>", meta_label),
            Paragraph("<b>Weight / Impact</b>", meta_label),
            Paragraph("<b>Assessment Classification</b>", meta_label),
        ],
        [
            Paragraph("<font color='#991b1b'><b>Critical</b></font>", body_style),
            Paragraph(f"<b>{crit_count}</b>", body_style),
            Paragraph("-25 pts each", body_style),
            Paragraph("Severe exploitability or missing critical isolation", body_style),
        ],
        [
            Paragraph("<font color='#c2410c'><b>High</b></font>", body_style),
            Paragraph(f"<b>{high_count}</b>", body_style),
            Paragraph("-15 pts each", body_style),
            Paragraph("Vulnerable components or missing core defenses", body_style),
        ],
        [
            Paragraph("<font color='#b45309'><b>Medium</b></font>", body_style),
            Paragraph(f"<b>{med_count}</b>", body_style),
            Paragraph("-8 pts each", body_style),
            Paragraph("Insecure cookies, cleartext transport, or weak headers", body_style),
        ],
        [
            Paragraph("<font color='#1e40af'><b>Low</b></font>", body_style),
            Paragraph(f"<b>{low_count}</b>", body_style),
            Paragraph("-3 pts each", body_style),
            Paragraph("Missing defense-in-depth header controls", body_style),
        ],
        [
            Paragraph("<font color='#475569'><b>Info</b></font>", body_style),
            Paragraph(f"<b>{info_count}</b>", body_style),
            Paragraph("0 pts", body_style),
            Paragraph("Informational security banners & observations", body_style),
        ],
        [
            Paragraph("<b>Total</b>", meta_label),
            Paragraph(f"<b>{total_findings}</b>", meta_label),
            Paragraph("", meta_label),
            Paragraph("", meta_label),
        ],
    ]

    sev_table = Table(sev_table_data, colWidths=[1.5 * inch, 1.0 * inch, 1.5 * inch, 3.0 * inch])
    sev_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
            ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#f8fafc")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ])
    )
    story.append(sev_table)
    story.append(Spacer(1, 16))

    # ── 6. Findings & Missing Controls ─────────────────────────────────────────
    story.append(Paragraph(f"Detailed Findings & Defensive Gaps ({total_findings})", section_heading))

    findings = report.get("findings_list") or []

    if not findings:
        clean_note = (
            "<b>No security weaknesses or missing defensive controls were observed.</b> "
            "The target application demonstrated full compliance with evaluated transport, "
            "cookie security, and HTTP defense-in-depth header standards."
        )
        story.append(Paragraph(clean_note, body_style))
        story.append(Spacer(1, 14))
    else:
        for idx, finding in enumerate(findings, start=1):
            f_title = _esc(finding.get("title", "Untitled finding"))
            f_sev = _esc((finding.get("severity") or "info").lower())
            f_type = finding.get("type", "missing_control")
            f_cat = _esc(finding.get("category", "general").capitalize())
            f_loc = _esc(finding.get("location", "N/A"))
            f_desc = _esc(finding.get("description", "")).replace("\n", "<br/>")
            f_evid = _esc(finding.get("evidence", "")).replace("\n", "<br/>")
            f_recom = _esc(finding.get("recommendation", "")).replace("\n", "<br/>")

            sev_color = SEVERITY_COLORS.get(f_sev, colors.HexColor("#475569"))
            sev_bg = SEVERITY_BG_COLORS.get(f_sev, colors.HexColor("#f1f5f9"))

            type_label = (
                "Confirmed Vulnerability" if f_type == "vulnerability" else "Missing Defensive Control"
            )

            # Finding card elements
            finding_elements: list[Any] = []

            # Finding title bar
            header_text = f"<b>#{idx} — {f_title}</b>"
            meta_sub = (
                f"<b>Severity:</b> <font color='{sev_color.hexval()}'><b>{f_sev.upper()}</b></font>  |  "
                f"<b>Classification:</b> {type_label}  |  "
                f"<b>Category:</b> {f_cat}  |  "
                f"<b>Location:</b> <font name='Courier'>{f_loc}</font>"
            )

            card_table_data = [
                [Paragraph(header_text, ParagraphStyle("FTitle", parent=body_style, fontName="Helvetica-Bold", fontSize=10, textColor=colors.HexColor("#0f172a")))],
                [Paragraph(meta_sub, ParagraphStyle("FMeta", parent=body_style, fontSize=8, textColor=colors.HexColor("#334155")))],
                [Paragraph(f"<b>Description:</b> {f_desc}", body_style)],
            ]

            if f_evid:
                card_table_data.append([
                    Paragraph(f"<b>Observed Evidence:</b><br/><font name='Courier'>{f_evid}</font>", code_style)
                ])

            if f_recom:
                card_table_data.append([
                    Paragraph(
                        f"<b>Remediation Recommendation:</b><br/><font color='#15803d'>{f_recom}</font>",
                        body_style,
                    )
                ])

            card_table = Table(card_table_data, colWidths=[7.0 * inch])
            card_table.setStyle(
                TableStyle([
                    ("BACKGROUND", (0, 0), (-1, 0), sev_bg),
                    ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#ffffff")),
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                    ("LINEBELOW", (0, 0), (-1, 0), 0.5, sev_color),
                    ("LINEBELOW", (0, 1), (-1, 1), 0.5, colors.HexColor("#e2e8f0")),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ("LEFTPADDING", (0, 0), (-1, -1), 8),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ])
            )

            finding_elements.append(card_table)
            finding_elements.append(Spacer(1, 10))

            # Keep individual finding intact on one page if possible
            story.append(KeepTogether(finding_elements))

    # ── 7. Scope & Legal Disclaimers ───────────────────────────────────────────
    disclaimer_box: list[Any] = [
        Paragraph("Assessment Scope, Methodology & Limitations", section_heading),
        Paragraph(
            "<b>Passive Audit Scope:</b> VulnWatch performs passive, non-destructive web security testing "
            "restricted strictly to loopback targets (localhost / 127.0.0.1 / ::1). It does not conduct invasive "
            "exploitation, automated denial-of-service, or third-party unauthorized probing.<br/>"
            "<b>Missing Controls vs. Vulnerabilities:</b> Observations marked as <i>Missing Defensive Control</i> "
            "represent absent defense-in-depth safeguards (e.g. absent Content-Security-Policy or HSTS headers) "
            "which elevate exposure, while items marked as <i>Confirmed Vulnerability</i> represent direct software "
            "or configuration weaknesses.<br/>"
            "<b>Static Dependency Baseline:</b> Dependency inspection references an offline sample advisory baseline "
            "for key framework packages and is not an exhaustive substitute for a live CVE threat intelligence feed.",
            ParagraphStyle("DiscText", parent=body_style, fontSize=7.5, leading=10, textColor=colors.HexColor("#64748b")),
        ),
    ]
    story.append(KeepTogether(disclaimer_box))

    # Build document with custom canvas
    doc.build(story, canvasmaker=NumberedCanvas)
    return buffer.getvalue()
